/**
 * Merges the per-module Prisma partials in prisma/ into a single
 * prisma/schema.prisma. Prisma requires one schema file, so edit the
 * *.prisma partials and run this script (or any prisma:* npm script,
 * which runs it first).
 */
const fs = require("fs");
const path = require("path");

const PRISMA_DIR = path.join(__dirname, "..", "prisma");

const PARTS = [
  "datasource.prisma",
  "user.prisma",
  "verification.prisma",
  "job.prisma",
  "task.prisma",
  "dispute.prisma",
  "finance.prisma",
];

const HEADER = `// ============================================================
// AUTO-GENERATED by scripts/merge-prisma-schema.cjs — DO NOT EDIT.
// Edit the *.prisma partials in prisma/ instead, then run:
//   npm run prisma:generate   (merges automatically)
// ============================================================
`;

const parts = PARTS.map((name) => {
  const filePath = path.join(PRISMA_DIR, name);
  if (!fs.existsSync(filePath)) {
    console.error(`Missing partial: ${name}`);
    process.exit(1);
  }
  return fs.readFileSync(filePath, "utf8").trim();
});

const merged = HEADER + parts.join("\n\n") + "\n";

if (!merged.includes("generator client")) {
  console.error("Merged schema is missing the generator block.");
  process.exit(1);
}
if (!merged.includes("datasource db")) {
  console.error("Merged schema is missing the datasource block.");
  process.exit(1);
}

fs.writeFileSync(path.join(PRISMA_DIR, "schema.prisma"), merged, "utf8");
console.log("Merged Prisma partials -> prisma/schema.prisma");